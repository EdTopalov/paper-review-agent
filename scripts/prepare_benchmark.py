"""Assemble the frozen benchmark; optional source rebuilding never invokes models."""

import argparse
import json
from pathlib import Path
import subprocess
import sys

from paper_review.benchmark_data import DEFAULT_BENCHMARK, freeze_catalog


SOURCE_BENCHMARK = Path(__file__).resolve().parents[1] / DEFAULT_BENCHMARK
MAINTAINED_READMES = ("README.md", "reviewcritique/README.md", "controlled/README.md", "selection/README.md")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_BENCHMARK)
    parser.add_argument("--rebuild-sources", action="store_true",
                        help="Download pinned public sources into a fresh output directory before assembly")
    args = parser.parse_args()
    if args.rebuild_sources:
        if args.out.exists():
            parser.error("Source rebuilding requires a fresh output directory")
        scripts = Path(__file__).resolve().parent
        for script, destination in (("prepare_qasper.py", args.out / "qasper"),
                                    ("prepare_reviewcritique.py", args.out / "reviewcritique"),
                                    ("prepare_controlled_benchmark.py", args.out)):
            subprocess.run([sys.executable, str(scripts / script), "--out", str(destination)], check=True)
        # These guides are maintained beside the frozen data, rather than
        # generated by a source adapter. Preserve their bytes during rebuilding.
        for relative in MAINTAINED_READMES:
            (args.out / relative).write_bytes((SOURCE_BENCHMARK / relative).read_bytes())
    print(json.dumps(freeze_catalog(args.out), indent=2))


if __name__ == "__main__":
    main()
